"""Run the automated test suite and write the observed results to docs/EVALUATION.md.

    python scripts/run_evaluation.py

Two runs are executed:
1. "public"  - EMPORIO_SKIP_ORIGINAL=1: what anyone gets from a fresh clone (synthetic fixtures);
2. "full"    - including the acceptance tests on the original challenge files, when present in data/.
Nothing in the report is typed by hand: counts come from pytest's JUnit XML.
"""

from __future__ import annotations

import datetime as dt
import os
import platform
import subprocess
import sys
import tempfile
import xml.etree.ElementTree as ET
from collections import defaultdict
from importlib import metadata
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]

REGRESSION_MAP = [
    ("1. Accessory questions returned instruments", "test_accessories_are_redirected_not_matched_to_instruments, "
     "test_instrument_name_containing_accessory_word_is_not_an_accessory, test_instrument_and_accessory_in_same_message"),
    ("2. Two-intent questions answered partially", "test_two_intents_price_and_hours, test_two_intents_returns_and_payment"),
    ("3. English questions not understood", "test_english_product_price_and_stock, test_english_category_budget_search, "
     "test_english_order_and_policy, test_language_switch"),
    ("4. Out-of-stock products announced as available", "test_out_of_stock_not_listed_and_flagged, "
     "test_discontinued_and_coming_soon_are_not_sellable, test_discontinued_bass_with_stock_is_not_sold"),
    ("5. Promotions applied outside validity", "test_inactive_promotion_is_reported_as_not_valid, "
     "test_inactive_promotions_are_never_applied"),
    ("6. Non-cumulative discounts violated", "test_pix_not_stacked_on_promotional_price, "
     "test_only_the_best_active_promotion_is_applied, test_taylor_promotion_not_stacked_with_pix"),
    ("7. Orders revealed without verification", "test_order_requires_email, test_order_with_wrong_email_reveals_nothing, "
     "test_order_lookup_attempts_are_limited, test_sessions_are_isolated"),
    ("8. Unverified information invented", "test_unknown_product_is_not_invented, test_empty_category_is_reported_honestly, "
     "test_freight_outside_metro_is_not_invented, test_live_tracking_is_not_claimed, "
     "test_hallucinated_price_falls_back_to_deterministic_answer"),
]


def run(label: str, extra_env: dict[str, str]) -> dict:
    with tempfile.TemporaryDirectory() as tmp:
        xml_path = Path(tmp) / "junit.xml"
        env = {**os.environ, **extra_env}
        env.pop("GEMINI_API_KEY", None)
        proc = subprocess.run([sys.executable, "-m", "pytest", "-q", "--color=no", "-p", "no:cacheprovider",
                               f"--junitxml={xml_path}"], cwd=ROOT, env=env, capture_output=True, text=True)
        root = ET.parse(xml_path).getroot()
    per_file: dict[str, dict[str, int]] = defaultdict(lambda: defaultdict(int))
    failures = []
    for case in root.iter("testcase"):
        module = case.get("classname", "").split(".")[-1]
        outcome = "passed"
        if case.find("failure") is not None or case.find("error") is not None:
            outcome = "failed"
            failures.append(f"{module}::{case.get('name')}")
        elif case.find("skipped") is not None:
            outcome = "skipped"
        per_file[module][outcome] += 1
    totals = defaultdict(int)
    for counts in per_file.values():
        for k, v in counts.items():
            totals[k] += v
    return {"label": label, "per_file": per_file, "totals": totals, "failures": failures,
            "summary": proc.stdout.strip().splitlines()[-1] if proc.stdout.strip() else "", "code": proc.returncode}


def version(pkg: str) -> str:
    try:
        return metadata.version(pkg)
    except metadata.PackageNotFoundError:
        return "not installed"


def main() -> int:
    has_original = any((ROOT / "data").glob("*.pdf"))
    runs = [run("Public clone (synthetic fixtures only)", {"EMPORIO_SKIP_ORIGINAL": "1"})]
    if has_original:
        runs.append(run("Full (synthetic fixtures + original challenge files in data/)", {}))
    now = dt.datetime.now().astimezone().strftime("%Y-%m-%d %H:%M %Z")
    lines = ["# Evaluation report", "",
             f"Generated by `scripts/run_evaluation.py` on {now}. All numbers below are parsed from pytest's JUnit "
             "XML output; nothing is typed by hand.", "",
             "## Environment", "",
             f"- Python {platform.python_version()} on {platform.system()} {platform.machine()}",
             "- " + ", ".join(f"{p} {version(p)}" for p in ("pandas", "pypdf", "google-genai", "gradio", "pytest")),
             "- `GEMINI_API_KEY` removed from the environment for the test runs (tests never call the real API).", "",
             "## Results", ""]
    for r in runs:
        t = r["totals"]
        lines += [f"### {r['label']}", "",
                  f"**{t['passed']} passed, {t['failed']} failed, {t['skipped']} skipped** "
                  f"(pytest exit code {r['code']}; `{r['summary']}`)", "",
                  "| Test module | Passed | Failed | Skipped |", "|---|---:|---:|---:|"]
        for module, counts in sorted(r["per_file"].items()):
            lines.append(f"| `{module}` | {counts['passed']} | {counts['failed']} | {counts['skipped']} |")
        if r["failures"]:
            lines += ["", "Failures:"] + [f"- `{f}`" for f in r["failures"]]
        lines.append("")
    lines += ["## Coverage of the previously reported failures", "",
              "| Reported failure | Regression tests |", "|---|---|"]
    lines += [f"| {name} | `{tests}` |" for name, tests in REGRESSION_MAP]
    lines += ["", "## What these tests do and do not prove", "",
              "- **Validated:** deterministic engine behaviour on synthetic fixtures and on the original snapshot; data "
              "loading/validation; business rules; BM25 retrieval and citations; guardrails; multi-turn state; the "
              "Gemini function-calling loop with the real `google-genai` request/response types and a scripted fake "
              "client (tool execution, e-mail tokenisation, grounding check, fallback, loop bound).",
              "- **Not validated here:** the behaviour of the hosted Gemini model (no API key was available in the "
              "development environment), execution inside Google Colab itself (the notebook was executed end-to-end "
              "with `jupyter nbconvert` in a Linux development environment, not in Colab), and load/concurrency behaviour of the Gradio app.",
              ""]
    out = ROOT / "docs" / "EVALUATION.md"
    out.write_text("\n".join(lines), encoding="utf-8")
    print(f"wrote {out}")
    for r in runs:
        print(r["label"], dict(r["totals"]))
    return max(r["code"] for r in runs)


if __name__ == "__main__":
    raise SystemExit(main())
